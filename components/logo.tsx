// Компонент логотипа "ÁCCENTS".
//
// Ударение сделано не отдельным элементом, а через саму букву:
// "Á" — это отдельный буквенный символ (как в испанском языке),
// у которого чёрточка ударения уже "нарисована" внутри самого шрифта.
// Так надёжнее, чем рисовать чёрточку отдельно через CSS — она никогда
// не съедет и не потеряется, потому что это часть буквы, а не отдельный
// элемент поверх неё.
//
// Пропс className — сюда снаружи передаются классы размера, шрифта,
// цвета и т.д. (например, "text-xl font-bold tracking-[0.3em]").
export function Logo({ className = "" }: { className?: string }) {
  return (
    <span className={`whitespace-nowrap ${className}`}>ÁCCENTS</span>
  )
}
